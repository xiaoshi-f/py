"""万物皆对象
类与对象,
类描述的是一组具有相同属性(特征)和方法(行为/功能)的模板
对象是类的实例,基于类创建出来的(实例对象)
类与对象：类是图纸，对象是按图纸造出来的东西
类（Class）：抽象的模板，定义了「有什么属性、能做什么事」
对象（Object / 实例）：具体的个体，占内存，有自己的数据
举例：类 = 汽车设计图，对象 = 你那辆具体的车

定义类
class 类名:
    pass


创建对象
对象名=类名()
对象名.属性名 = 属性值     动态添加属性
 """
# 类与对象  实例对象  魔法方法   实例属性与类属性
# 类与对象

# 定义类
class Car:
    pass

c1= Car()
# 动态添加属性
c1.brand ="BWM"
print(c1.__dict__)# 将对象中的所有的属性以字典的形式输出出来