# ==================== break 终止当前所在的循环 ====================
# 说明：break 是一个控制流语句，用于（立即终止当前所在的循环）比如（for 循环或者 while 循环），
#       跳出循环体，继续执行循环之后的代码
# 关键点：
#   1. 作用范围：break 只能在循环内部（for / while），如果在循环外使用会报错
#   2. 立刻退出：一旦执行 break，循环就会立刻结束，无论循环条件是否仍然满足
#   3. 只影响当前循环：如果存在嵌套循环，break 只会退出最近的一层循环
a = 0
while a < 5:
    if a == 3:
        break
    a = a + 1
    print(f'a的值是{a}')
print('循环结束')

